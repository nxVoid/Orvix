"""Validate authored studio products and embed their versioned runtime assets."""
import base64
import hashlib
import json
import re
from pathlib import Path
from xml.etree import ElementTree as ET

ROOT = Path(__file__).resolve().parents[2]
STUDIO = ROOT / "docs/cosmetics-studio"
ANIMATION = {"animate", "animateTransform", "animateMotion", "set"}
ET.register_namespace("", "http://www.w3.org/2000/svg")


def static_svg(source: str) -> str:
    root = ET.fromstring(source)
    for parent in root.iter():
        for child in list(parent):
            if child.tag.rsplit("}", 1)[-1] in ANIMATION:
                parent.remove(child)
    return ET.tostring(root, encoding="unicode")


def validate_svg(source: str):
    if re.search(r"<!DOCTYPE|<!ENTITY", source, re.I):
        raise ValueError("External XML declarations are forbidden")
    root = ET.fromstring(source)
    for element in root.iter():
        tag = element.tag.rsplit("}", 1)[-1]
        if tag in {"script", "foreignObject", "iframe", "style"}:
            raise ValueError(f"Forbidden SVG tag {tag}")
        for key, value in element.attrib.items():
            key = key.rsplit("}", 1)[-1]
            if key.lower().startswith("on"):
                raise ValueError(f"Forbidden event attribute {key}")
            if key in {"href", "src"} and not value.startswith(("data:image/webp;base64,", "data:image/png;base64,", "#")):
                raise ValueError("SVG images must be embedded WebP assets")
            if "url(" in value.replace("url(#", ""):
                raise ValueError("External paint URL")


def build():
    collection = json.loads((STUDIO / "manifests/collection-v2.json").read_text())
    registry = {}
    additions = []
    for product in collection["products"]:
        folder = STUDIO / product["directory"]
        metadata = json.loads((folder / "metadata.json").read_text())
        if metadata["id"] != product["id"]:
            raise ValueError("Product identity mismatch")
        for role in ["asset", "poster"]:
            name = metadata[role]
            path = folder / name
            if path.parent != folder or not re.fullmatch(r"[a-z0-9_-]+\.(svg|webp)", name):
                raise ValueError(f"Unsafe runtime asset filename {name}")
            data = path.read_bytes()
            if len(data) > metadata["budgets"]["max_asset_bytes"]:
                raise ValueError(f"Asset budget exceeded by {path}")
            mime = "image/svg+xml" if path.suffix == ".svg" else "image/webp"
            if path.suffix == ".svg":
                validate_svg(data.decode())
            registry[name] = {"mime": mime, "data": base64.b64encode(data).decode()}
        if metadata.get("collection_id") == "relay_gallery" and metadata.get("quality_state") == "reviewed":
            additions.append({
                "id": metadata["id"], "name": metadata["name"],
                "category": metadata["category"], "rarity": metadata["rarity"],
                "price": metadata["price_rp"], "premium": metadata["premium"],
                "asset": "/economy/assets/" + metadata["asset"],
                "static_asset": "/economy/assets/" + metadata["poster"],
                "animated": metadata.get("animated", False),
                "collection_id": metadata["collection_id"],
            })
        product["asset"] = "/economy/assets/" + metadata["asset"]
        product["static_asset"] = "/economy/assets/" + metadata["poster"]
        product["quality_state"] = metadata["quality_state"]
        product["sha256"] = hashlib.sha256((folder / metadata["poster"]).read_bytes()).hexdigest()
    destination = ROOT / "relay_api/src/api/economy/StudioAssetRegistry.ts"
    destination.write_text(
        "// SPDX-License-Identifier: AGPL-3.0-or-later\n"
        "// Generated by tools/relay/build-cosmetics-studio.py.\n"
        "export const STUDIO_ASSETS: Readonly<Record<string, {mime: string; data: string}>> = "
        + json.dumps(registry, indent="\t") + ";\n"
        "export const STUDIO_UPGRADES = " + json.dumps([
            {"id": p["id"], "asset": p["asset"], "static_asset": p["static_asset"]}
            for p in collection["products"] if p.get("quality_state") == "reviewed"
        ], indent="\t") + ";\n"
        + "export const STUDIO_PRODUCTS = " + json.dumps(additions, indent="\t", ensure_ascii=False) + ";\n"
    )
    (STUDIO / "manifests/collection-v2.json").write_text(json.dumps(collection, indent=2) + "\n")
    print(f"Validated {len(collection['products'])} products and embedded {len(registry)} assets")


if __name__ == "__main__":
    build()
