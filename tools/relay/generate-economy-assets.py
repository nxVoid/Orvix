"""Embed the original Relay artwork and derive reduced-motion variants."""

import json
from pathlib import Path
from xml.etree import ElementTree

ROOT = Path(__file__).resolve().parents[2]
REFERENCE = ROOT / "docs/references/spark/Relay_Cosmetics_Workspace"
DESTINATION = ROOT / "relay_api/src/api/economy"
SVG = "http://www.w3.org/2000/svg"
ANIMATION_TAGS = {"animate", "animateTransform", "animateMotion", "set"}
DISALLOWED_TAGS = {"script", "foreignObject", "iframe", "image", "use", "style"}
PREMIUM_ITEMS = {"amethyst_crown", "prism_core", "eclipse", "eclipse_plate"}


def local_name(qualified_name: str) -> str:
    return qualified_name.rsplit("}", 1)[-1]


def read_asset(path: Path) -> tuple[str, str]:
    source = path.read_text(encoding="utf-8")
    if "<!DOCTYPE" in source.upper() or "<!ENTITY" in source.upper():
        raise ValueError(f"Unexpected XML declaration in {path}")
    root = ElementTree.fromstring(source)
    if root.tag != f"{{{SVG}}}svg":
        raise ValueError(f"Expected an SVG document in {path}")
    for element in root.iter():
        if local_name(element.tag) in DISALLOWED_TAGS:
            raise ValueError(f"Unsupported SVG element in {path}: {element.tag}")
        for key, value in element.attrib.items():
            attribute = local_name(key).lower()
            if attribute.startswith("on") or attribute in {"href", "src", "style"}:
                raise ValueError(f"Unsupported SVG attribute in {path}: {key}")
            if "url(" in value.replace("url(#", ""):
                raise ValueError(f"Nonlocal SVG reference in {path}")
        for child in list(element):
            if local_name(child.tag) in ANIMATION_TAGS:
                element.remove(child)
    return source, ElementTree.tostring(root, encoding="unicode")


def build_catalog():
    catalog = json.loads((REFERENCE / "catalog.json").read_text(encoding="utf-8"))
    assets = {}
    products = []
    for item in catalog:
        path = REFERENCE / item["asset"]
        if path.suffix != ".svg" or not path.resolve().is_relative_to(REFERENCE):
            raise ValueError(f"Unexpected asset path {path}")
        static_name = f"{path.stem}-static.svg"
        assets[path.name], assets[static_name] = read_asset(path)
        category = item["type"]
        if category == "banner" and item["animated"]:
            category = "animated_banner"
        if item["id"] == "relay_aurora":
            category = "profile_theme"
        products.append(
            {
                "id": item["id"],
                "name": item["name"],
                "description": "Relay Origins koleksiyonu",
                "category": category,
                "rarity": item["rarity"],
                "price": item["price_rp"],
                "asset": f"/economy/assets/{path.name}",
                "static_asset": f"/economy/assets/{static_name}",
                "animated": item["animated"],
                "premium": item["id"] in PREMIUM_ITEMS,
                "published": True,
                "stock": None,
                "collection_id": "relay_origins",
                "event_label": None,
                "starts_at": None,
                "ends_at": None,
                "sold": 0,
            }
        )
    return assets, products


def write_typescript(filename: str, declaration: str, value, imports: str = ""):
    (DESTINATION / filename).write_text(
        "// SPDX-License-Identifier: AGPL-3.0-or-later\n"
        "// Generated by tools/relay/generate-economy-assets.py.\n\n"
        + imports
        + f"export const {declaration} = "
        + json.dumps(value, ensure_ascii=False, indent="\t")
        + ";\n",
        encoding="utf-8",
    )


if __name__ == "__main__":
    ElementTree.register_namespace("", SVG)
    assets, products = build_catalog()
    write_typescript("EconomyAssets.ts", "ECONOMY_ASSETS: Readonly<Record<string, string>>", assets)
    write_typescript(
        "EconomyCatalog.ts",
        "INITIAL_COSMETICS: ReadonlyArray<Cosmetic>",
        products,
        "import type {Cosmetic} from './EconomyService';\n\n",
    )
    print(f"Audited {len(products)} original assets and generated {len(assets)} variants")
