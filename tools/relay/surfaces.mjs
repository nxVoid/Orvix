import fs from 'node:fs';
import {createRequire} from 'node:module';
import path from 'node:path';
import {edit, root, write} from './workspace.mjs';

const sharp = createRequire(path.join(root, 'relay_api/package.json'))('sharp');
const mark = await sharp(path.join(root, 'branding/relay-logo.png')).resize(192, 192, {fit: 'inside'}).png().toBuffer();
write(
	'relay_app/src/media/RelayLogoData.ts',
	`// Generated by tools/relay/surfaces.mjs from branding/relay-logo.png.\nexport const RELAY_LOGO_DATA_URL = 'data:image/png;base64,${mark.toString('base64')}';\n`,
);
edit('relay_app/src/features/auth/utils/RecoveryKitSheet.ts', (s) =>
	s
		.replace(
			'// SPDX-License-Identifier: AGPL-3.0-or-later',
			"// SPDX-License-Identifier: AGPL-3.0-or-later\n\nimport {RELAY_LOGO_DATA_URL} from '@app/media/RelayLogoData';",
		)
		.replace(
			'const writer = new SheetWriter(pdf, fonts);',
			`const writer = new SheetWriter(pdf, fonts);
 // Embed locally: PDF generation never sends the recovery key to an image service.
 const relayMark = await pdf.embedPng(RELAY_LOGO_DATA_URL);
 const logoSize = relayMark.scaleToFit(48, 48);
 writer.currentPage.drawImage(relayMark, {x: MARGIN, y: writer.y - logoSize.height, ...logoSize});
 writer.y -= logoSize.height + 12;`,
		),
);
edit('relay_app/scripts/build/rspack/static-files.mjs', (s) =>
	s.replace(/(name|short_name): 'Orvix'/g, "$1: 'Relay'").replace('Orvix is', 'Relay is'),
);
edit('relay_desktop/src/main/Autostart.ts', (s) => s.replace('Comment=Orvix', 'Comment=Relay'));
edit('tools/ci/src/desktop.rs', (s) => {
	const start = s.indexOf('"stable" => ("relay_desktop"');
	if (start < 0) throw new Error('Windows package identity mapping moved; review required');
	const end = s.indexOf('};', start);
	const fragment = s.slice(start, end).replaceAll('Orvix', 'Relay');
	s = s.slice(0, start) + fragment + s.slice(end);
	// Assertions describing current output names, not old manifest/archive compatibility fixtures.
	return s
		.replace('stable.main_exe, "Orvix.exe"', 'stable.main_exe, "Relay.exe"')
		.replace('canary.main_exe, "Orvix Canary.exe"', 'canary.main_exe, "Relay Canary.exe"')
		.replace('development.pack_title, "Orvix Development"', 'development.pack_title, "Relay Development"')
		.replace('development.artifact_prefix, "Relay-Development"', 'development.artifact_prefix, "Relay-Development"')
		.replace('development.main_exe, "Orvix Development.exe"', 'development.main_exe, "Relay Development.exe"');
});
// Keep legal terms/versioned history and executable commands unchanged in current docs.
const walk = (dir) =>
	fs
		.readdirSync(dir, {withFileTypes: true})
		.flatMap((e) =>
			e.name === 'node_modules' || e.name.startsWith('.')
				? []
				: e.isDirectory()
					? walk(path.join(dir, e.name))
					: [path.join(dir, e.name)],
		);
for (const file of walk(path.join(root, 'relay_docs'))) {
	const name = path.relative(root, file);
	if (!/\.mdx?$/.test(name) || /changelog|legal|licen[cs]e|terms|\/versions\//i.test(name)) continue;
	edit(name, (s) => {
		let fenced = false;
		return s
			.split('\n')
			.map((line) => {
				if (/^\s*(```|~~~)/.test(line)) {
					fenced = !fenced;
					return line;
				}
				if (fenced || /copyright|Fluxer Platform AB|upstream|fork of|original author/i.test(line)) return line;
				const protectedParts = [];
				const held = line.replace(
					/`[^`]+`|https?:\/\/[^\s)<>]+|[\w.+-]+@[\w.-]+/g,
					(m) => `__BRAND_HOLD_${protectedParts.push(m) - 1}__`,
				);
				return held
					.replace(/\b(?:Orvix|Fluxer)\b/g, 'Relay')
					.replace(/__BRAND_HOLD_(\d+)__/g, (_, n) => protectedParts[+n]);
			})
			.join('\n');
	});
}
console.log('Updated recovery PDF, PWA, installer display mapping and current narrative documentation.');
